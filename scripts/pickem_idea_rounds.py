"""Round-by-round hypotheses for the situational idea search.

Imported by scripts/pickem_idea_lab.py, which owns the data loading, the
holdout guard rail, the flipped-games evaluation and the multiplicity ledger.
Each round appends its experiments here so the whole search stays reproducible
and so PICKEM_MODEL.md's tables can be regenerated by one command.

Ideas come from a domain-expert agent that reads PICKEM_MODEL.md fresh each
round and is deliberately kept naive to the model's internals, so it proposes
football/market reasoning rather than variations on what already ships.
"""
from __future__ import annotations

import math

from edge.pickem import _coinflip_side, make_pick

MEAN_TOTAL = 44.0     # league-typical projected total, used as the centering point


def _shipped(g):
    return make_pick(g["away"], g["home"], g["pool_line"], g["live_line"],
                     g["total_open"], g["total_close"])


def _moved(g, floor=0.5):
    return abs(g["move"]) >= floor


def _dtotal(g):
    if g["total_open"] is None or g["total_close"] is None:
        return None
    return g["total_close"] - g["total_open"]


def _fade(g):
    """The opposite of whatever the shipped model would pick."""
    return "away" if _shipped(g).side == "home" else "home"


def _primetime(g):
    if g["weekday"] in ("Thursday", "Monday", "Saturday"):
        return True
    t = g["gametime"] or ""
    if g["weekday"] == "Sunday" and ":" in t:
        try:
            return int(t.split(":")[0]) >= 19
        except ValueError:
            return False
    return False


def _ols(ys, xcols):
    """Least squares with intercept, via normal equations. Returns [b0, b1, ...]."""
    n = len(ys)
    k = len(xcols) + 1
    X = [[1.0] + [c[i] for c in xcols] for i in range(n)]
    XtX = [[sum(X[i][a] * X[i][b] for i in range(n)) for b in range(k)] for a in range(k)]
    Xty = [sum(X[i][a] * ys[i] for i in range(n)) for a in range(k)]
    for c in range(k):                                   # gaussian elimination
        p = max(range(c, k), key=lambda r: abs(XtX[r][c]))
        XtX[c], XtX[p] = XtX[p], XtX[c]
        Xty[c], Xty[p] = Xty[p], Xty[c]
        if abs(XtX[c][c]) < 1e-12:
            return [0.0] * k
        for r in range(k):
            if r == c:
                continue
            f = XtX[r][c] / XtX[c][c]
            for cc in range(c, k):
                XtX[r][cc] -= f * XtX[c][cc]
            Xty[r] -= f * Xty[c]
    return [Xty[i] / XtX[i][i] for i in range(k)]


def _corr(a, b):
    n = len(a)
    if n < 3:
        return 0.0
    ma, mb = sum(a) / n, sum(b) / n
    num = sum((x - ma) * (y - mb) for x, y in zip(a, b))
    da = math.sqrt(sum((x - ma) ** 2 for x in a))
    db = math.sqrt(sum((y - mb) ** 2 for y in b))
    return num / (da * db) if da and db else 0.0


def _split(rows, TRAIN):
    return ([g for g in rows if g["season"] in TRAIN],
            [g for g in rows if g["season"] not in TRAIN])


# ============================================================== SANITY ======

def sanity(rows, ledger, evaluate, report, header):
    """Harness self-tests. Not hypotheses -- never registered in the ledger."""
    header("HARNESS SANITY CHECKS (not registered as hypotheses)")
    report(evaluate(rows, "null rule (always defer to shipped)", lambda g: None),
           ledger, register=False)
    report(evaluate(rows, "inverted shipped (should be strongly negative)", _fade),
           ledger, register=False)
    report(evaluate(rows, "placebo (parity of len(home team code))",
                    lambda g: ("home" if len(g["home"]) % 2 == 0 else "away")
                    if _shipped(g).tier == "COIN FLIP" else None),
           ledger, register=False)


# ============================================================== ROUND 1 =====

def round1(rows, ledger, evaluate, report, header):
    TRAIN = set(range(2014, 2020))
    tr, va = _split(rows, TRAIN)

    header("ROUND 1 -- KILL TESTS (single regressions, run before any pick machinery)")

    # --- K1: does the spread scale with the scoring environment? -----------
    print("\n  K1. Does true margin scale with the projected total?")
    print("      regress margin ~ pool_line + pool_line*(total_open - 44), TRAIN only")
    for lab, sub in (("TRAIN", tr), ("VALIDATE", va)):
        d = [g for g in sub if g["total_open"] is not None]
        ys = [g["margin"] for g in d]
        x1 = [g["pool_line"] for g in d]
        x2 = [g["pool_line"] * (g["total_open"] - MEAN_TOTAL) for g in d]
        b = _ols(ys, [x1, x2])
        # beta expressed per point of total, relative to the main line coefficient
        rel = b[2] / b[1] if b[1] else 0.0
        print(f"      [{lab:<8}] b_line={b[1]:+.4f}  b_interaction={b[2]:+.5f}  "
              f"implied beta={rel:+.5f} per pt of total")

    # --- K2: does the market move the SPREAD for wind, or only the TOTAL? --
    print("\n  K2. Wind: does the market move the total for it (yes?) and the spread (no?)")
    out = [g for g in rows if g["outdoor"] and g["wind"] is not None
           and g["total_open"] is not None and g["total_close"] is not None]
    print(f"      outdoor dev games with wind recorded: {len(out)}")
    print(f"      corr(wind, total_close-total_open) = "
          f"{_corr([g['wind'] for g in out], [_dtotal(g) for g in out]):+.3f}   "
          f"(expect NEGATIVE if the market learns wind in-week)")
    print(f"      corr(wind, |spread move|)          = "
          f"{_corr([g['wind'] for g in out], [abs(g['move']) for g in out]):+.3f}")
    print(f"      corr(wind, signed move toward dog) = "
          f"{_corr([g['wind'] for g in out], [g['move'] if g['pool_line'] < 0 else -g['move'] for g in out]):+.3f}")
    print("      mean |total move| by wind bucket:")
    for lo, hi in ((0, 9), (9, 13), (13, 18), (18, 99)):
        s = [g for g in out if lo <= g["wind"] < hi]
        if not s:
            continue
        print(f"        wind {lo:>2}-{hi:<3} n={len(s):4d}  "
              f"mean dtotal {sum(_dtotal(g) for g in s)/len(s):+5.2f}  "
              f"dog cover vs frozen "
              f"{sum(1 for g in s if g['home_covers'] is not None and ((g['pool_line']>0)==g['home_covers']))/max(1,sum(1 for g in s if g['home_covers'] is not None)):5.1%}")
    print("      DOME PLACEBO (must be flat -- these games have no wind):")
    dome = [g for g in rows if not g["outdoor"] and g["total_open"] is not None]
    dw = sum(1 for g in dome if g["home_covers"] is not None
             and ((g["pool_line"] > 0) == g["home_covers"]))
    dn = sum(1 for g in dome if g["home_covers"] is not None)
    print(f"        dome/closed n={dn}  dog cover {dw/dn:.1%}")

    header("ROUND 1 -- PICK-RULE TESTS (each registered in the multiplicity ledger)")

    # --- 1. Total-corroboration gate ---------------------------------------
    print("\n  Idea 1: fade the spread move when the TOTAL did not corroborate it.")
    print("  (info moves are subtractive -> total falls; money moves leave the total alone)")
    for lo, hi, lab in ((1.0, 99.0, "total ROSE >=1.0 (money move -> fade)"),
                        (-99.0, -1.0, "total FELL >=1.0 (info move -> follow, control)")):
        d = [g for g in rows if _moved(g) and _dtotal(g) is not None
             and lo <= _dtotal(g) < hi and g["home_covers"] is not None]
        w = sum(1 for g in d if (_shipped(g).side == "home") == g["home_covers"])
        print(f"    descriptive: {lab:<45} shipped goes {w}-{len(d)-w} "
              f"({w/len(d):.1%}, n={len(d)})")

    report(evaluate(rows, "R1.1 fade move when total ROSE >=1.0",
                    lambda g: _fade(g) if (_moved(g) and _dtotal(g) is not None
                                           and _dtotal(g) >= 1.0) else None,
                    round_no=1), ledger)

    # --- 2. Scoring-environment scaling of the frozen line ------------------
    print("\n  Idea 2: scale the frozen spread by the projected scoring environment.")
    d = [g for g in tr if g["total_open"] is not None]
    b = _ols([g["margin"] for g in d], [[g["pool_line"] for g in d],
             [g["pool_line"] * (g["total_open"] - MEAN_TOTAL) for g in d]])
    beta = (b[2] / b[1]) if b[1] else 0.0
    beta_used = beta / 2                    # 5d: halve any dev-fitted magnitude
    print(f"    beta fitted on TRAIN = {beta:+.5f}/pt; applying halved {beta_used:+.5f}")

    def env_side(g):
        if g["total_open"] is None:
            return None
        env_edge = g["pool_line"] * beta_used * (g["total_open"] - MEAN_TOTAL)
        combined = g["move"] + env_edge
        if abs(combined) < 0.5:
            return None
        return "home" if combined < 0 else "away"

    report(evaluate(rows, "R1.2 environment-scaled line (total_open)", env_side,
                    round_no=1, notes=f"beta={beta_used:+.5f} halved from train"), ledger)

    # --- 3. Wind helps the underdog ----------------------------------------
    print("\n  Idea 3: high wind -> low scoring -> compressed margin -> underdog.")
    for thr in (13, 15):
        report(evaluate(rows, f"R1.3 outdoor wind>={thr} -> take the underdog",
                        lambda g, t=thr: (("home" if g["pool_line"] > 0 else "away")
                                          if (g["outdoor"] and g["wind"] is not None
                                              and g["wind"] >= t) else None),
                        round_no=1), ledger)

    # --- 4. Primetime shading ----------------------------------------------
    print("\n  Idea 4: fade small primetime moves toward the favourite (public shading).")

    def toward_fav(g):
        return (g["live_line"] < 0 and g["move"] < 0) or (g["live_line"] > 0 and g["move"] > 0)

    def pt_rule(g):
        return (_fade(g) if (_primetime(g) and _moved(g) and abs(g["move"]) <= 1.5
                             and toward_fav(g)) else None)

    report(evaluate(rows, "R1.4 fade small primetime moves toward favourite",
                    pt_rule, round_no=1), ledger)
    print("    CONTROL -- identical rule on 1pm Sunday games (no shading mechanism;")
    print("    if this fires too, the effect belongs to move size, not primetime):")
    report(evaluate(rows, "R1.4c CONTROL same rule on 1pm Sunday games",
                    lambda g: (_fade(g) if (not _primetime(g) and g["weekday"] == "Sunday"
                                            and _moved(g) and abs(g["move"]) <= 1.5
                                            and toward_fav(g)) else None),
                    round_no=1), ledger)

    # --- 5. Backup-QB over-adjustment --------------------------------------
    print("\n  Idea 5: does the market over-adjust when a starting QB is ruled out?")
    prev_qb = {}
    qb_change = {}
    for g in sorted(rows, key=lambda g: (g["season"], g["week"])):
        for side in ("home", "away"):
            team = g[side]
            qb = g[f"{side}_qb"]
            k = (g["season"], team)
            if k in prev_qb and qb and prev_qb[k] and qb != prev_qb[k]:
                qb_change[(g["season"], g["week"], team)] = True
            if qb:
                prev_qb[k] = qb

    def qb_lost(g, side):
        return qb_change.get((g["season"], g["week"], g[side]), False)

    n_ch = sum(1 for g in rows if qb_lost(g, "home") or qb_lost(g, "away"))
    print(f"    QB differs from that team's previous game: {n_ch} dev games "
          f"({16*n_ch/len(rows):.1f}/week)")

    def qb_rule(g):
        # market moved >=2 pts AWAY from the team with the new QB -> take that team
        if qb_lost(g, "home") and not qb_lost(g, "away") and g["move"] >= 2.0:
            return "home"
        if qb_lost(g, "away") and not qb_lost(g, "home") and g["move"] <= -2.0:
            return "away"
        return None

    report(evaluate(rows, "R1.5 back the team whose QB changed when line moved >=2 vs them",
                    qb_rule, round_no=1), ledger)

    # --- 6. Divisional rematch after a blowout ------------------------------
    print("\n  Idea 6: divisional rematch after a lopsided first meeting.")
    first = {}
    for g in sorted(rows, key=lambda g: (g["season"], g["week"])):
        key = (g["season"], frozenset((g["home"], g["away"])))
        if key not in first:
            first[key] = g

    def rematch_rule(g):
        if not g["div_game"]:
            return None
        key = (g["season"], frozenset((g["home"], g["away"])))
        m1 = first.get(key)
        if m1 is None or m1 is g or m1["week"] >= g["week"]:
            return None
        if abs(m1["margin"]) < 14:
            return None
        winner = m1["home"] if m1["margin"] > 0 else m1["away"]
        loser = m1["away"] if m1["margin"] > 0 else m1["home"]
        if g["home"] == loser:
            return "home"
        if g["away"] == loser:
            return "away"
        return None

    report(evaluate(rows, "R1.6 divisional rematch: back meeting-1 blowout LOSER",
                    rematch_rule, round_no=1), ledger)
    print("    CONTROL -- same rule where meeting 1 was decided by <7 (should be nothing):")

    def rematch_control(g):
        if not g["div_game"]:
            return None
        key = (g["season"], frozenset((g["home"], g["away"])))
        m1 = first.get(key)
        if m1 is None or m1 is g or m1["week"] >= g["week"] or abs(m1["margin"]) >= 7:
            return None
        loser = m1["away"] if m1["margin"] > 0 else m1["home"]
        return "home" if g["home"] == loser else ("away" if g["away"] == loser else None)

    report(evaluate(rows, "R1.6c CONTROL rematch after a CLOSE first meeting",
                    rematch_control, round_no=1), ledger)

    # R1.6 was consistently NEGATIVE in both eras (z=-2.02/-2.06, 0/9 seasons),
    # which is itself a directional claim: the inverse should then be positive.
    # Pre-registered follow-up rather than a fishing expedition -- a reliably
    # wrong rule and a reliably right one are the same finding with a sign.
    print("\n    INVERSE of R1.6 -- back the meeting-1 blowout WINNER instead:")

    def rematch_winner(g):
        if not g["div_game"]:
            return None
        key = (g["season"], frozenset((g["home"], g["away"])))
        m1 = first.get(key)
        if m1 is None or m1 is g or m1["week"] >= g["week"] or abs(m1["margin"]) < 14:
            return None
        winner = m1["home"] if m1["margin"] > 0 else m1["away"]
        return "home" if g["home"] == winner else ("away" if g["away"] == winner else None)

    report(evaluate(rows, "R1.6i INVERSE: back meeting-1 blowout WINNER",
                    rematch_winner, round_no=1), ledger)


# ============================================================== ROUND 2 =====

def _keyzone(g):
    """True if a key number (3 or 7, either sign) lies in or on the move's span."""
    lo, hi = min(g["pool_line"], g["live_line"]), max(g["pool_line"], g["live_line"])
    return any(lo <= k <= hi for k in (3.0, 7.0, -3.0, -7.0))


def _tiebreak_side(g):
    """What the shipped totals-drift tiebreak would say, ignoring the move."""
    return _coinflip_side(g["live_line"], g["total_open"], g["total_close"])


def _window(g):
    if g["weekday"] != "Sunday":
        return "non-Sunday"
    t = g["gametime"] or ""
    try:
        h = int(t.split(":")[0])
    except (ValueError, IndexError):
        return "unknown"
    return "Sun-early" if h < 16 else "Sun-late"


def round2(rows, ledger, evaluate, report, header):
    TRAIN = set(range(2014, 2020))

    header("ROUND 2 -- the half-point zone, the deadline, and the tiebreak's holes")

    n = len(rows)
    half = [g for g in rows if abs(g["move"]) == 0.5]
    flat = [g for g in rows if abs(g["move"]) < 0.5]
    print(f"\n  Exposure reframing: |move|=0.5 -> {len(half)} games ({16*len(half)/n:.2f}/wk); "
          f"|move|<0.5 -> {len(flat)} ({16*len(flat)/n:.2f}/wk)")
    print(f"  Combined {100*(len(half)+len(flat))/n:.1f}% of the slate has <=0.5 pts of signal.")

    # --- 1. Is a half-point move information, or vig management? -----------
    print("\n  Idea 1: treat |move|=0.5 as NO signal; route it to the totals tiebreak.")
    for lab, sel in (("|move|=0.5", lambda g: abs(g["move"]) == 0.5),
                     ("|move|=1.0", lambda g: abs(g["move"]) == 1.0),
                     ("|move|>=1.5", lambda g: abs(g["move"]) >= 1.5)):
        d = [g for g in rows if sel(g) and g["home_covers"] is not None]
        w = sum(1 for g in d if (_shipped(g).side == "home") == g["home_covers"])
        print(f"    descriptive: following the move on {lab:<12} "
              f"{w}-{len(d)-w} ({w/len(d):.1%}, n={len(d)})")

    report(evaluate(rows, "R2.1 route |move|=0.5 to the totals tiebreak",
                    lambda g: _tiebreak_side(g) if abs(g["move"]) == 0.5 else None,
                    round_no=2), ledger)

    report(evaluate(rows, "R2.1b same, only FLAT-ZONE halves (no key number in span)",
                    lambda g: (_tiebreak_side(g) if (abs(g["move"]) == 0.5
                                                     and not _keyzone(g)) else None),
                    round_no=2), ledger)

    print("    CONTROL -- route 1.0-pt moves to the tiebreak too. If this ALSO helps,")
    print("    the finding is 'the tiebreak beats small moves generally', not a")
    print("    half-point quantum effect:")
    report(evaluate(rows, "R2.1c CONTROL route |move|=1.0 to the tiebreak",
                    lambda g: _tiebreak_side(g) if abs(g["move"]) == 1.0 else None,
                    round_no=2), ledger)

    # --- 2. The 2x2 of spread direction x total direction -------------------
    print("\n  Idea 2: 2x2 grid -- spread move direction x total move direction.")
    print("  (recreational money takes the favourite AND the over on the same game)")

    def cell(g):
        if abs(g["move"]) < 0.5 or _dtotal(g) is None:
            return None
        to_fav = ((g["live_line"] < 0 and g["move"] < 0)
                  or (g["live_line"] > 0 and g["move"] > 0))
        dt = _dtotal(g)
        if abs(dt) < 0.5:
            return None
        return ("toFAV" if to_fav else "toDOG") + ("_totUP" if dt > 0 else "_totDN")

    for c in ("toFAV_totUP", "toFAV_totDN", "toDOG_totUP", "toDOG_totDN"):
        line = f"    {c:<12}"
        for lab, seas in (("train", TRAIN), ("val", None)):
            d = [g for g in rows if cell(g) == c and g["home_covers"] is not None
                 and ((g["season"] in TRAIN) if seas else (g["season"] not in TRAIN))]
            w = sum(1 for g in d if (_shipped(g).side == "home") == g["home_covers"])
            line += f"  {lab} {w/len(d):5.1%} (n={len(d):3d})" if d else f"  {lab} n/a"
        print(line)
    report(evaluate(rows, "R2.2 fade the toFAV_totUP cell (max-recreational signature)",
                    lambda g: _fade(g) if cell(g) == "toFAV_totUP" else None,
                    round_no=2), ledger)

    # --- 3. The deadline is not the close -----------------------------------
    print("\n  Idea 3: the pick deadline is each day's first kickoff, NOT the close.")
    print("  If late-window games win more at matched move size, that surplus is")
    print("  post-deadline information we will NOT have live.")
    for wlab in ("Sun-early", "Sun-late", "non-Sunday"):
        line = f"    {wlab:<11}"
        for mlab, msel in (("coinflip", lambda g: abs(g["move"]) < 0.5),
                           ("0.5-1.5", lambda g: 0.5 <= abs(g["move"]) <= 1.5),
                           ("2.0+", lambda g: abs(g["move"]) >= 2.0)):
            d = [g for g in rows if _window(g) == wlab and msel(g)
                 and g["home_covers"] is not None]
            w = sum(1 for g in d if (_shipped(g).side == "home") == g["home_covers"])
            line += f"  {mlab} {w/len(d):5.1%} (n={len(d):4d})" if d else f"  {mlab} n/a"
        print(line)
    print("    ^ the coin-flip column is the CONTROL: no movement signal exists there,")
    print("      so any window gap in it is a scheduling artifact (NFL flexes good games")
    print("      late) and must be subtracted before reading the moving columns.")

    report(evaluate(rows, "R2.3 raise threshold to 1.5 on Sunday-late games",
                    lambda g: (_tiebreak_side(g) if (_window(g) == "Sun-late"
                                                     and 0.5 <= abs(g["move"]) < 1.5)
                               else None), round_no=2), ledger)

    # --- 4. Fade small moves toward a team off a blowout win ----------------
    print("\n  Idea 4: fade small moves toward a team coming off a blowout WIN.")
    prev_margin = {}
    for g in sorted(rows, key=lambda g: (g["season"], g["week"])):
        g["_home_prev"] = prev_margin.get((g["season"], g["home"]))
        g["_away_prev"] = prev_margin.get((g["season"], g["away"]))
        prev_margin[(g["season"], g["home"])] = g["margin"]
        prev_margin[(g["season"], g["away"])] = -g["margin"]

    def blowout_rule(g, thr=14, lo=0.5, hi=1.0, sign=1):
        if not (lo <= abs(g["move"]) <= hi):
            return None
        toward = "home" if g["move"] < 0 else "away"
        prev = g["_home_prev"] if toward == "home" else g["_away_prev"]
        if prev is None or sign * prev < thr:
            return None
        return "away" if toward == "home" else "home"

    for thr in (14, 17, 21):
        report(evaluate(rows, f"R2.4 fade small move toward team off a >={thr} win",
                        lambda g, t=thr: blowout_rule(g, t), round_no=2), ledger)
    print("    CONTROL (a) symmetry -- same rule toward a team off a >=14 LOSS:")
    report(evaluate(rows, "R2.4a CONTROL toward team off a >=14 LOSS",
                    lambda g: blowout_rule(g, 14, sign=-1), round_no=2), ledger)
    print("    CONTROL (b) magnitude -- same rule on LARGE moves (>=2), which should")
    print("    be news-driven and immune:")
    report(evaluate(rows, "R2.4b CONTROL same rule on |move|>=2",
                    lambda g: blowout_rule(g, 14, lo=2.0, hi=99.0), round_no=2), ledger)

    # --- 5a. The tiebreak's fall-through -----------------------------------
    print("\n  Idea 5a: when spread AND total are both flat, the model falls through to")
    print("  'take the market favourite' -- the rule this doc measures at 48.3% on dev.")
    ft = [g for g in rows if abs(g["move"]) < 0.5 and _dtotal(g) is not None
          and abs(_dtotal(g)) < 0.5]
    print(f"    fall-through games: {len(ft)} ({16*len(ft)/n:.2f}/wk)")
    report(evaluate(rows, "R2.5a fall-through -> take the underdog instead",
                    lambda g: (("home" if g["pool_line"] > 0 else "away")
                               if (abs(g["move"]) < 0.5 and _dtotal(g) is not None
                                   and abs(_dtotal(g)) < 0.5) else None),
                    round_no=2), ledger)

    # --- 5b. Referee crew home-lean ----------------------------------------
    print("\n  Idea 5b: referee crew home-lean, as-of-week, heavily shrunk, coin flips only.")
    crew = {}
    leans = {}
    for g in sorted(rows, key=lambda g: (g["season"], g["week"])):
        r = g["referee"]
        if r:
            w, nn = crew.get(r, (0, 0))
            leans[id(g)] = (w - nn / 2) / (nn + 50) if nn else 0.0   # shrunk toward 0
            if g["home_covers"] is not None:
                crew[r] = (w + (1 if g["home_covers"] else 0), nn + 1)
        else:
            leans[id(g)] = 0.0

    def ref_rule(g):
        if _shipped(g).tier != "COIN FLIP":
            return None
        lean = leans.get(id(g), 0.0)
        if abs(lean) < 0.02:
            return None
        return "home" if lean > 0 else "away"

    report(evaluate(rows, "R2.5b referee crew home-lean on coin flips", ref_rule,
                    round_no=2), ledger)


