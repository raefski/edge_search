def round4(rows, ledger, evaluate, report, header):
    """The tournament question: is the pool a prediction task or a rank task?

    NOT agent-scouted -- the round-4 scout was cut off by an API spend limit,
    so this pursues the fully-specified thread left by round 3's scout rather
    than substituting a less-independent idea generator. Flagged because the
    value of rounds 1-3 came from the scout being NAIVE to this model, and
    that property is absent here.

    THE CONFOUND THAT HAD TO BE REMOVED (kept as a comment because it is the
    kind of mistake that looks like a result): simulating with the REAL
    flat-zone outcomes credits each policy with whatever that policy happened
    to score on dev. The shipped tiebreak went 57.3% train / 49.0% validate --
    a sign flip, i.e. noise -- but pooled to 54.4%, so the simulation handed
    it a spurious win-rate advantage and the shadow benefit appeared to
    REVERSE at reduced edge. Randomising flat-zone outcomes to true coin
    flips gives all policies identical expected wins, leaving correlation
    with the field as the only difference. That is the effect being measured.
    """
    import numpy as np

    TRAIN = set(range(2014, 2020))
    header("ROUND 4 -- the pool is a TOURNAMENT: are coin-flip picks free?")

    live = [g for g in rows if g["home_covers"] is not None]
    flat = [g for g in live if _shipped(g).tier == "COIN FLIP"]

    print("\n  A. Flat-zone EV with a confidence interval. If it brackets 50%, those")
    print("     ~3 picks/week are FREE and can be spent on rank instead of on wins.")
    for lab, sel in (("TRAIN", lambda g: g["season"] in TRAIN),
                     ("VALIDATE", lambda g: g["season"] not in TRAIN),
                     ("DEV pooled", lambda g: True)):
        d = [g for g in flat if sel(g)]
        w = sum(1 for g in d if (_shipped(g).side == "home") == g["home_covers"])
        n = len(d); p = w / n; se = (0.25 / n) ** 0.5
        print(f"     {lab:<11} {w}-{n-w}  {p:.1%}  "
              f"95% CI [{p-1.96*se:.1%}, {p+1.96*se:.1%}]  n={n}")
    for lab, fn in (("always favourite", lambda g: "away" if g["pool_line"] > 0 else "home"),
                    ("always underdog", lambda g: "home" if g["pool_line"] > 0 else "away")):
        line = f"     {lab:<18}"
        for elab, sel in (("train", lambda g: g["season"] in TRAIN),
                          ("val", lambda g: g["season"] not in TRAIN)):
            d = [g for g in flat if sel(g)]
            w = sum(1 for g in d if (fn(g) == "home") == g["home_covers"])
            line += f"  {elab} {w/len(d):5.1%} (n={len(d)})"
        print(line)
    print("     ^ all three sign-flip between eras. Flat-zone EV is 50%.")

    by_season = {}
    for g in live:
        by_season.setdefault(g["season"], []).append(g)
    S = []
    for _, games in sorted(by_season.items()):
        sig = np.array([_shipped(g).tier != "COIN FLIP" for g in games])
        ok = np.array([(_shipped(g).side == "home") == g["home_covers"] for g in games])
        fc = np.array([(("away" if g["pool_line"] > 0 else "home") == "home")
                       == g["home_covers"] for g in games])
        S.append((sig, ok, fc))

    def sim(top, edge_scale, lo, hi, n_sim=20000, n_opp=17, seed=11):
        rng = np.random.default_rng(seed)
        out = {p: [] for p in ("current", "shadow", "diverge")}
        for sig, ok_sig, favc in S:
            nflat = int((~sig).sum()); n_sig = int(sig.sum())
            f_sig = int(favc[sig].sum())
            nr = int(ok_sig[sig].sum()); nw = n_sig - nr
            keep = edge_scale + (1 - edge_scale) * 0.5
            truth = rng.random((n_sim, nflat)) < 0.5     # flat games: fresh coin flips
            lean = rng.uniform(lo, hi, size=(n_sim, n_opp))
            opp = rng.binomial(f_sig, lean) + rng.binomial(n_sig - f_sig, 1 - lean)
            for i in range(n_opp):
                opp[:, i] += ((rng.random((n_sim, nflat)) < lean[:, i][:, None])
                              == truth).sum(axis=1)
            my_sig = (rng.binomial(nr, keep, size=n_sim)
                      + rng.binomial(nw, (1 - edge_scale) * 0.5, size=n_sim))
            for p in out:
                if p == "shadow":
                    mf = truth.sum(axis=1)
                elif p == "diverge":
                    mf = (~truth).sum(axis=1)
                else:
                    mf = ((rng.random((n_sim, nflat)) < 0.5) == truth).sum(axis=1)
                my = my_sig + mf
                out[p].append(((1 + (opp > my[:, None]).sum(axis=1)) <= top).mean())
        return {p: float(np.mean(v)) for p, v in out.items()}

    print("\n  B. PURE tournament effect -- flat-zone outcomes randomised to true coin")
    print("     flips, so all policies have identical expected WINS and differ only in")
    print("     correlation with the field. P(top 4 of 18), 20k sims/season.")
    print(f"\n     {'field':<22} {'edge':<6} {'current':>8} {'shadow':>8} "
          f"{'diverge':>8} {'shadow-current':>16}")
    for flab, (lo, hi) in (("weak (lean .55-.90)", (0.55, 0.90)),
                           ("realistic (.70-.95)", (0.70, 0.95)),
                           ("sharp (.85-1.00)", (0.85, 1.00))):
        for elab, es in (("full", 1.0), ("60%", 0.6), ("30%", 0.3)):
            r = sim(4, es, lo, hi)
            print(f"     {flab:<22} {elab:<6} {r['current']:>7.1%} {r['shadow']:>8.1%} "
                  f"{r['diverge']:>8.1%} {100*(r['shadow']-r['current']):>+15.2f}pp")
    print("     ^ shadow wins in EVERY cell with a real edge, and the advantage GROWS")
    print("       as the field gets sharper -- the signature of a correlation effect.")

    print("\n  B2. Adam CANNOT see his pool's picks pre-lock (confirmed 2026-08-23), so")
    print("      the strategy must run on CBS's NATIONAL percentage. Does that cost much?")
    print("      oracle = shadow the realised 18-person majority (impossible in practice)")
    print("      prior  = shadow the a-priori popular side (what he can actually do)")

    def sim2(edge_scale, lo, hi, n_sim=20000, n_opp=17, top=4, seed=13):
        rng = np.random.default_rng(seed)
        out = {p: [] for p in ("current", "prior", "oracle")}
        for sig, ok_sig, favc in S:
            nflat = int((~sig).sum()); n_sig = int(sig.sum())
            f_sig = int(favc[sig].sum())
            nr = int(ok_sig[sig].sum()); nw = n_sig - nr
            keep = edge_scale + (1 - edge_scale) * 0.5
            truth = rng.random((n_sim, nflat)) < 0.5
            lean = rng.uniform(lo, hi, size=(n_sim, n_opp))
            opp = rng.binomial(f_sig, lean) + rng.binomial(n_sig - f_sig, 1 - lean)
            took = np.empty((n_sim, n_opp, nflat), dtype=bool)
            for i in range(n_opp):
                took[:, i, :] = rng.random((n_sim, nflat)) < lean[:, i][:, None]
                opp[:, i] += (took[:, i, :] == truth).sum(axis=1)
            majority = took.sum(axis=1) > (n_opp / 2)
            my_sig = (rng.binomial(nr, keep, size=n_sim)
                      + rng.binomial(nw, (1 - edge_scale) * 0.5, size=n_sim))
            for p in out:
                if p == "prior":
                    mf = truth.sum(axis=1)
                elif p == "oracle":
                    mf = (majority == truth).sum(axis=1)
                else:
                    mf = ((rng.random((n_sim, nflat)) < 0.5) == truth).sum(axis=1)
                my = my_sig + mf
                out[p].append(((1 + (opp > my[:, None]).sum(axis=1)) <= top).mean())
        return {p: float(np.mean(v)) for p, v in out.items()}

    print(f"\n      {'field':<22} {'edge':<6} {'current':>8} {'prior':>8} {'oracle':>8} "
          f"{'prior captures':>16}")
    for flab, (lo, hi) in (("weak (.55-.90)", (0.55, 0.90)),
                           ("realistic (.70-.95)", (0.70, 0.95)),
                           ("sharp (.85-1.00)", (0.85, 1.00))):
        for elab, es in (("full", 1.0), ("60%", 0.6)):
            r = sim2(es, lo, hi)
            go = r["oracle"] - r["current"]; gp = r["prior"] - r["current"]
            frac = (gp / go * 100) if abs(go) > 1e-9 else float("nan")
            print(f"      {flab:<22} {elab:<6} {r['current']:>7.1%} {r['prior']:>8.1%} "
                  f"{r['oracle']:>8.1%} {frac:>15.0f}%")
    print("      ^ 96-100%. With 18 opponents who lean the same way, the realised")
    print("        majority IS the popular side, so observing it adds ~nothing.")

    print("\n  C. Does it flip for a winner-take-all prize? (realistic field, full edge)")
    print(f"     {'prize shape':<26} {'current':>8} {'shadow':>8} {'diverge':>8}   best")
    for top, lab in ((1, "1st only (weekly prize)"), (2, "top 2"),
                     (4, "top 4 (season money)"), (8, "top 8 (beat the median)")):
        r = sim(top, 1.0, 0.70, 0.95)
        print(f"     {lab:<26} {r['current']:>7.1%} {r['shadow']:>8.1%} "
              f"{r['diverge']:>8.1%}   {max(r, key=r.get)}")
    print("     ^ does NOT flip, but the edge shrinks as the target narrows. Correct:")
    print("       variance-seeking is for UNDERDOGS, and this model is the field's")
    print("       favourite. Section 7's chase mode covers the behind-late case.")


